export function t(lang, key, params) {
  const pack = DICT[normalizeLang(lang)] || hy;
  const value = pack[key] ?? hy[key] ?? key;
  if (typeof value === 'function') return value(params || {});
  if (!params) return value;
  return String(value).replace(/\{(\w+)\}/g, (_, name) => (params[name] == null ? '' : String(params[name])));
}

export function hasKey(key) {
  return Object.prototype.hasOwnProperty.call(hy, key);
}

export function statusLabel(lang, value) {
  const key = `status.${value}`;
  return hasKey(key) ? t(lang, key) : (value || '');
}

export function orderStatus(lang, value) {
  const key = `order.${value}`;
  return hasKey(key) ? t(lang, key) : (value || '');
}

export function planPoint(lang, point) {
  const row = POINTS[point];
  if (!row) return point;
  return row[normalizeLang(lang)] || point;
}

export function hasError(message) {
  return Object.prototype.hasOwnProperty.call(ERRORS, String(message || ''));
}

export function translateError(lang, code, message) {
  const safe = normalizeLang(lang);
  const text = String(message || '');
  const row = ERRORS[text];
  if (row) {
    if (safe === 'hy') return row.hy || text;
    return row[safe] || text;
  }
  if (safe === 'hy') return text;
  return text;
}

export function missingKeys() {
  const base = Object.keys(hy);
  const gaps = [];
  for (const [name, dict] of [['en', en], ['ru', ru]]) {
    for (const key of base) if (!(key in dict)) gaps.push(`${name}:${key}`);
    for (const key of Object.keys(dict)) if (!(key in hy)) gaps.push(`extra ${name}:${key}`);
  }
  return gaps;
}
